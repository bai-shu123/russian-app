const fs = require('fs');
const path = require('path');
const vm = require('vm');

const projectRoot = path.resolve(__dirname, '..');
const courseSource = fs.readFileSync(path.join(projectRoot, 'course.js'), 'utf8');
const context = {};
vm.runInNewContext(`${courseSource}\nthis.__courseBooks = courseBooks;`, context, {
  filename: 'course.js'
});

const cleanLine = value => String(value || '').replace(/^[—–-]+\s*/, '').trim();
const difficultyFor = (bookIndex, lessonIndex) => {
  if (bookIndex === 0) return lessonIndex < 8 ? 'A2 基础' : 'A2 巩固';
  return lessonIndex < 3 ? 'A2 巩固' : 'A2→B1';
};
const knowledgeTags = (lesson, source) => {
  const tags = [];
  (lesson.grammar || []).slice(0, 3).forEach(item => tags.push({ type: '语法', name: item.title }));
  if (source === 'dialogue') tags.push({ type: '句型', name: lesson.subtitle || lesson.title });
  tags.push({ type: '词汇', name: lesson.title.replace(/^第\s*\d+\s*课[:：]?\s*/, '') });
  return tags;
};

const rows = [];
context.__courseBooks.forEach((book, bookIndex) => {
  book.lessons.forEach((lesson, lessonIndex) => {
    const examples = [];
    (lesson.grammar || []).forEach(group => {
      (group.examples || []).forEach(item => examples.push({ item, source: 'grammar', group: group.title }));
    });
    if (lesson.text && lesson.text.lines) {
      lesson.text.lines.forEach(item => examples.push({ item, source: 'dialogue', group: lesson.text.title }));
    }
    examples.forEach(({ item, source, group }, index) => {
      const answerRu = cleanLine(item.ru);
      const promptZh = cleanLine(item.zh);
      if (!answerRu || !promptZh || answerRu.length < 2) return;
      ['translation', 'dictation'].forEach(type => rows.push({
        id: ['seed', book.id, lesson.id, source, index, type].join('-'),
        version: 1,
        status: 'published',
        visibility: 'public',
        type,
        prompt_zh: promptZh,
        answer_ru: answerRu,
        accepted_answers: [],
        explanation: group || '',
        book_id: book.id,
        book_title: book.title,
        lesson_id: String(lesson.id),
        lesson_title: lesson.title,
        difficulty: difficultyFor(bookIndex, lessonIndex),
        knowledge_tags: knowledgeTags(lesson, source),
        source: 'course'
      }));
    });
  });
});

const selected = rows.filter(row => row.book_id === 'russian-road-2').slice(0, 60);
if (!selected.length) throw new Error('No second-book training exercises were generated.');

const payload = JSON.stringify(selected).replace(/\$seed\$/g, '$ seed $');
const sql = `-- Generated by tools/generate-training-seed.js. Existing exercises are preserved.
with seed as (
  select * from jsonb_to_recordset($seed$${payload}$seed$::jsonb) as item(
    id text, version integer, status text, visibility text, type text,
    prompt_zh text, answer_ru text, accepted_answers jsonb, explanation text,
    book_id text, book_title text, lesson_id text, lesson_title text,
    difficulty text, knowledge_tags jsonb, source text
  )
)
insert into public.training_exercises (
  id, version, status, visibility, type, prompt_zh, answer_ru,
  accepted_answers, explanation, book_id, book_title, lesson_id,
  lesson_title, difficulty, knowledge_tags, source, published_at
)
select
  id, version, status, visibility, type, prompt_zh, answer_ru,
  accepted_answers, explanation, book_id, book_title, lesson_id,
  lesson_title, difficulty, knowledge_tags, source, now()
from seed
on conflict (id) do nothing;

select count(*) as published_training_exercises
from public.training_exercises
where status = 'published' and deleted_at is null;
`;

const outputPath = path.resolve(process.argv[2] || path.join(projectRoot, 'supabase', '.temp', 'training-seed.sql'));
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, sql, 'utf8');
console.log(`Generated ${selected.length} exercises at ${outputPath}`);
